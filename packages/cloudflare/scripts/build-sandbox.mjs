// Bundles the Code node sandbox (src/runtime/code-sandbox/sandbox-entry.ts) into a string module.
// The worker passes this string to the Worker Loader for each Code task.
// It also collects the Python sandbox: python-entry.py and the stock Python runner modules it imports.
import { mkdtemp, readdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { bundle } from '../build.mjs';

/** Writes and renames, so that a concurrent build never reads a partial file. */
async function writeGenerated(destination, content) {
	const temporary = `${destination}.${process.pid}.tmp`;
	await writeFile(temporary, `// Generated by scripts/build-sandbox.mjs. Do not edit.\n${content}`);
	await rename(temporary, destination);
}

const directory = await mkdtemp(join(tmpdir(), 'n8n-code-sandbox-'));
try {
	const outfile = join(directory, 'sandbox.js');
	await bundle({ entry: 'src/runtime/code-sandbox/sandbox-entry.ts', outfile, external: ['n8n-code.cjs'] });
	const source = await readFile(outfile, 'utf8');
	await writeGenerated('src/runtime/code-sandbox/bundle.generated.ts', `export const SANDBOX_SOURCE = ${JSON.stringify(source)};\n`);
	console.log(`Code sandbox: ${(source.length / 1024).toFixed(0)} KiB`);
} finally {
	await rm(directory, { recursive: true, force: true });
}

// The modules of the task executor and its imports. The broker connection, health check and Sentry stay out.
const PYTHON_RUNNER = '../@n8n/task-runner-python/src';
const PYTHON_FILES = [
	'__init__.py',
	'constants.py',
	'_sandbox_callables.py',
	'format_validation.py',
	'import_validation.py',
	'pipe_reader.py',
	'task_analyzer.py',
	'task_executor.py',
	'config/__init__.py',
	'config/security_config.py',
	...(await readdir(join(PYTHON_RUNNER, 'errors'))).filter((name) => name.endsWith('.py')).map((name) => `errors/${name}`),
	...(await readdir(join(PYTHON_RUNNER, 'message_types'))).filter((name) => name.endsWith('.py')).map((name) => `message_types/${name}`),
].sort();
const pythonModules = { 'n8n_python.py': await readFile('src/runtime/code-sandbox/python-entry.py', 'utf8') };
for (const file of PYTHON_FILES) pythonModules[`src/${file}`] = await readFile(join(PYTHON_RUNNER, file), 'utf8');
await writeGenerated(
	'src/runtime/code-sandbox/python.generated.ts',
	`export const PYTHON_MAIN_MODULE = 'n8n_python.py';\nexport const PYTHON_MODULES: Record<string, string> = ${JSON.stringify(pythonModules, null, '\t')};\n`,
);
const pythonSize = Object.values(pythonModules).reduce((total, text) => total + text.length, 0);
console.log(`Python sandbox: ${(pythonSize / 1024).toFixed(0)} KiB`);
